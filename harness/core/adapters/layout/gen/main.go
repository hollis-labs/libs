package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/hollis-labs/substrate/harness/adapters/layout/plan"
)

const (
	docPath      = "adapters/layout/docs/LAYOUT.md"
	jsonPath     = "adapters/layout/layout.json"
	planDocPath  = "adapters/layout/docs/PLAN-FIELDS.md"
	planJSONPath = "adapters/layout/plan-fields.json"
)

func main() {
	check := flag.Bool("check", false, "fail when the generated files are stale instead of writing them")
	root := flag.String("root", "", "module root (default: nearest directory with go.mod)")
	flag.Parse()
	if *root == "" {
		r, err := findRoot()
		if err != nil {
			fmt.Fprintln(os.Stderr, "layout/gen:", err)
			os.Exit(2)
		}
		*root = r
	}
	stale, err := run(*root, *check)
	if err != nil {
		fmt.Fprintln(os.Stderr, "layout/gen:", err)
		os.Exit(2)
	}
	if len(stale) > 0 {
		fmt.Fprintf(os.Stderr, "layout/gen: stale: %s (run: go generate ./...)\n", strings.Join(stale, ", "))
		os.Exit(1)
	}
}

func findRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no go.mod above the working directory; pass -root")
		}
		dir = parent
	}
}

// run writes (or, with check, compares) the generated files under root and
// returns the paths that differ.
func run(root string, check bool) ([]string, error) {
	outputs, err := renderPlan()
	if err != nil {
		return nil, err
	}
	var stale []string
	for _, rel := range []string{planDocPath, planJSONPath} {
		want := outputs[rel]
		full := filepath.Join(root, filepath.FromSlash(rel))
		got, readErr := os.ReadFile(full)
		if readErr == nil && bytes.Equal(got, want) {
			continue
		}
		if check {
			stale = append(stale, rel)
			continue
		}
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return nil, err
		}
		if err := os.WriteFile(full, want, 0o644); err != nil {
			return nil, err
		}
	}
	return stale, nil
}

func fileMode(m uint32) string {
	if m == 0 {
		return ""
	}
	return fmt.Sprintf("%04o", m)
}

func escape(v string) string {
	r := strings.NewReplacer("|", `\|`, "\n", " ", "<", "&lt;", ">", "&gt;")
	return r.Replace(v)
}

// renderPlan exports the sole authored plan-field table.
func renderPlan() (map[string][]byte, error) {
	rows := plan.Table()
	if err := plan.Validate(rows); err != nil {
		return nil, err
	}
	data, err := json.MarshalIndent(struct {
		Schema string      `json:"schema"`
		Rows   []exportRow `json:"rows"`
	}{Schema: "provider-plan-fields.v1", Rows: exportedRows(rows)}, "", "  ")
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("# Provider layout plan fields\n\n")
	b.WriteString("<!-- Code generated by go run ./adapters/layout/gen; DO NOT EDIT. Source: adapters/layout/plan/table.go -->\n\n")
	b.WriteString("This is the sole authored provider layout plan-field table, distinct from a workspace or launch plan. Compatibility modes and operator MCP mirrors preserve existing adapter projections without a second placement table. Older layout exports are historical evidence.\n\n")
	b.WriteString("Rows select provider, layer, transport and optional variant. Empty transport means the layer default; more specific transport and variant rows override it. Paths are relative to logical roots supplied by the host. Native documents compose only under an explicit serializer owner. Credential destinations are link effects and never managed file writes. Unsupported capabilities refuse required requests or name optional omissions. See [package documentation](../plan/doc.go) for intended output changes and support boundaries.\n\n")
	b.WriteString("| provider | layer | mode | variant | field | concern | root | path | form | mode bits | capability | owner / composition | native slot | exclusive MCP | credential policy | runtime reference | locator | evidence |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n")
	for _, r := range rows {
		locator, err := json.Marshal(r.Locator)
		if err != nil {
			return nil, err
		}
		ref := ""
		if r.Posture != nil {
			ref = string(r.Posture.Provider) + ": " + r.Posture.Mapper
		}
		evidence := r.Evidence.Reference
		if len(r.Evidence.Observations) > 0 {
			evidence += " (" + strings.Join(r.Evidence.Observations, ", ") + ")"
		}
		if r.Evidence.Note != "" {
			evidence += "; " + r.Evidence.Note
		}
		if r.Reason != "" {
			evidence += "; " + r.Reason
		}
		values := []string{string(r.Provider), string(r.Layer), string(r.Mode), string(r.Variant), string(r.Field), r.Concern, string(r.Root), r.Path, string(r.Form), fileMode(r.ModeBits), string(r.Capability), r.Renderer + " / " + r.Composition, r.DocumentSlot, string(r.ExclusiveMCP), string(r.CredentialPolicy), ref, string(locator), evidence}
		for i := range values {
			values[i] = escape(values[i])
		}
		b.WriteString("| " + strings.Join(values, " | ") + " |\n")
	}
	return map[string][]byte{planJSONPath: append(data, '\n'), planDocPath: []byte(b.String())}, nil
}

type exportRow struct {
	plan.Row
	ModeBits              string `json:"mode_bits"`
	CompatibilityModeBits uint32 `json:"compatibility_mode_bits,omitempty"`
	CompatibilityMCPPath  string `json:"compatibility_mcp_path,omitempty"`
}

func exportedRows(rows []plan.Row) []exportRow {
	out := make([]exportRow, len(rows))
	for i, r := range rows {
		out[i] = exportRow{Row: r, ModeBits: fmt.Sprintf("%04o", r.ModeBits), CompatibilityModeBits: r.CompatibilityModeBits, CompatibilityMCPPath: r.CompatibilityMCPPath}
	}
	return out
}
